def test_prior_density_is_the_truncated_renormalised_prior():
    import numpy as np

    from pirao.core.preview import prior_density

    x = np.linspace(0.0, 1.0, 2001)
    pdf = prior_density("lognormal", {"mu": 0.0, "sigma": 1.0}, 0.0, 1.0, x)
    assert np.trapezoid(pdf, x) == pytest.approx(1.0, abs=2e-3)
    flat = prior_density("flat", {}, 2.0, 4.0, np.array([1.0, 3.0, 5.0]))
    assert list(flat) == [0.0, 0.5, 0.0]
    assert prior_density("flat", {}, 0.0, None, x) is None


def test_kaplan_meier_handles_censoring_and_weights():
    from types import SimpleNamespace

    from pirao.core.results import kaplan_meier

    def fake(rows):
        lik = SimpleNamespace(mission="time")
        return SimpleNamespace(
            resolved=SimpleNamespace(likelihood=lik),
            spec=SimpleNamespace(prior_only=False),
            table=SimpleNamespace(rows=rows),
        )

    rows = [
        {"time": 1.0, "failure": 1, "relevance": 1.0},
        {"time": 2.0, "failure": 0, "relevance": 1.0},
        {"time": 3.0, "failure": 1, "relevance": 1.0},
        {"time": 4.0, "failure": 1, "relevance": 1.0},
    ]
    km = kaplan_meier(fake(rows))
    # 4 at risk, 1 fails -> 3/4; one censored; 2 at risk, 1 fails -> 3/8; then 0.
    assert [s["s"] for s in km["steps"]] == pytest.approx([1.0, 0.75, 0.375, 0.0])
    assert km["censored"] == [{"t": 2.0, "s": 0.75}]
    half = kaplan_meier(fake([dict(r, relevance=0.5) for r in rows]))
    assert [s["s"] for s in half["steps"]] == pytest.approx([1.0, 0.75, 0.375, 0.0])


def test_every_registry_text_has_a_portuguese_translation():
    """A new or reworded English string must come with its Portuguese."""
    from pirao.api.main import get_meta
    from pirao.locales import missing

    meta = get_meta()
    texts = []
    for lik in meta["likelihoods"]:
        texts += [lik["label"], lik["description"]]
