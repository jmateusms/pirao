def test_retained_mass_detects_a_badly_truncated_prior():
    lognormal = get_prior("lognormal")
    assert retained_mass(
        lognormal, {"mu": 0.0, "sigma": 1.0}, 0.0, 1.0
    ) == pytest.approx(0.5, abs=1e-3)
    assert retained_mass(
        lognormal, {"mu": -6.0, "sigma": 1.0}, 0.0, 1.0
    ) == pytest.approx(1.0, abs=1e-6)


def test_half_families_on_their_natural_support_lose_no_mass():
    # Emitted as the symmetric density on a parameter bounded at 0, but the
    # prior the user chose is the half one, so [0, inf) keeps all of it.
    for family in ("half_normal", "half_cauchy"):
        assert retained_mass(
            get_prior(family), {"sigma": 2.0}, 0.0, None
        ) == pytest.approx(1.0)
    assert retained_mass(
        get_prior("half_normal"), {"sigma": 1.0}, 0.0, 1.0
    ) == pytest.approx(0.6827, abs=1e-3)


def test_the_preview_describes_the_truncated_prior_not_the_entered_one():
    preview = prior_preview("lognormal", {"mu": 0.0, "sigma": 1.0}, 0.0, 1.0)
    assert preview.retained_mass == pytest.approx(0.5, abs=1e-3)
    assert preview.median < 1.0  # the untruncated median is exactly 1.0
    assert preview.warning and "keep only" in preview.warning


def test_an_improper_family_previews_as_a_warning_until_bounded():
    unbounded = prior_preview("flat", {}, 0.0, None)
    assert not unbounded.is_proper and unbounded.warning

    bounded = prior_preview("flat", {}, 2.0, 6.0)
    assert bounded.median == pytest.approx(4.0)
    assert bounded.pdf and all(math.isclose(p, 0.25) for p in bounded.pdf)


