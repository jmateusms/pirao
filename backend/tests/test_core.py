def test_bounds_are_intersected_with_the_prior_support():
    spec = spec_for("bernoulli_geometric")
    spec.params["prob"] = ParamSpec(
        lower=0.1, prior=PriorSpec(family="beta", hyper={"a": 2.0, "b": 2.0})
    )
    param = resolve(spec).param("prob")
    assert param.lo == 0.1
    assert param.hi == 1.0  # clamped by both the role and the beta support


