@pytest.mark.parametrize("likelihood", sorted(LIKELIHOODS))
def test_the_data_dict_matches_the_generated_data_block(likelihood):
    """Every declared data variable must be supplied, and nothing extra.

    Derived from the generated source rather than maintained by hand -- this is
    the second-easiest place in the project to be silently wrong.
    """
    spec = spec_for(likelihood)
    rendered = render(spec)
    _, examples = template_rows(likelihood)
    table = validate_table(spec, examples)
    data = to_stan_data(spec, table)

    declared: set[str] = set()
    inside = False
    for line in rendered.source.splitlines():
        stripped = line.strip()
        if stripped.startswith("data {"):
            inside = True
            continue
        if inside and stripped == "}":
            break
        if not inside or not stripped or stripped.startswith("//"):
            continue
        name = stripped.split("//")[0].strip().rstrip(";").split()[-1]
        declared.add(name.split("[")[0])

    assert declared, "no data block was parsed"
    assert declared == set(data), (
        f"{likelihood}: declared-but-missing={sorted(declared - set(data))}, "
        f"supplied-but-undeclared={sorted(set(data) - declared)}"
    )


