def spec_for(likelihood: str, **overrides) -> ModelSpec:
    """A minimal valid spec, so tests only state what they are about."""
    lik = get_likelihood(likelihood)
    defaults = {
        "rate": PriorSpec(family="gamma", hyper={"shape": 2.0, "rate": 0.01}),
        "scale": PriorSpec(family="gamma", hyper={"shape": 2.0, "rate": 0.01}),
        "shape": PriorSpec(family="half_normal", hyper={"sigma": 2.0}),
        "prob": PriorSpec(family="beta", hyper={"a": 1.0, "b": 1.0}),
        "mu": PriorSpec(family="normal", hyper={"mu": 5.0, "sigma": 2.0}),
        "sigma": PriorSpec(family="half_normal", hyper={"sigma": 1.0}),
    }
    params = {
        p.name: ParamSpec(
            lower=0.0 if p.nat_lo == 0.0 else None, prior=defaults[p.name]
        )
        for p in lik.params
    }
    kwargs: dict = {"likelihood": likelihood, "params": params}
    if lik.mission == "time":
        kwargs["mission_times"] = [100.0]
    else:
        kwargs["mission_demands"] = 1
    kwargs.update(overrides)
    return ModelSpec(**kwargs)


