@pytest.mark.slow
def test_a_run_completes_and_exposes_its_artifacts():
    response = client.post(
        "/api/runs",
        json={
            "spec": _spec(),
            "rows": [
                {"device": "A", "time": 120.0, "failure": 1},
                {"device": "B", "time": 300.0, "failure": 0},
                {"device": "C", "time": 45.0, "failure": 1, "relevance": 0.8},
            ],
            "sampler": {
                "chains": 2,
                "iter_warmup": 400,
                "iter_sampling": 400,
                "seed": 7,
            },
        },
    )
    assert response.status_code == 200
    run_id = response.json()["id"]

    deadline = time.time() + 240
    while time.time() < deadline:
        state = client.get(f"/api/runs/{run_id}").json()
        if state["status"] in ("done", "failed", "cancelled"):
            break
        time.sleep(0.5)

    assert state["status"] == "done", state.get("error")
    assert state["seed"] == 7  # the resolved seed is recorded for reproducibility

    names = {row["parameter"] for row in state["summary"]["table"]}
    assert "rate" in names
    assert state["summary"]["reliability_curve"][0]["mission_time"] == 100.0

    # Reliability is reported against the mission it answers for, not against
    # the position it happened to occupy in a Stan vector.
    assert "reliability(t=100 h)" in names
    assert not any(name.startswith("reliability[") for name in names)

    over_time = state["summary"]["reliability_over_time"]
    assert over_time["kind"] == "time"
    assert over_time["mission"] == [100.0]
    assert over_time["points"][0]["x"] == 0.0
    assert over_time["points"][0]["mean"] == pytest.approx(1.0)
    assert over_time["points"][-1]["x"] == pytest.approx(130.0)  # 1.3 x mission
    # Reliability only falls.
    means = [point["mean"] for point in over_time["points"]]
    assert means == sorted(means, reverse=True)

    posterior = client.get(f"/api/runs/{run_id}/posterior").json()
    assert posterior["parameters"] == ["rate"]
    assert len(posterior["columns"]["rate"]) > 100
    # The curve is 121 columns of picture; it belongs in the summary, not in
    # the browser's copy of the draws.
    assert not any("reliability_curve" in name for name in posterior["columns"])

    assert "weibull" not in client.get(f"/api/runs/{run_id}/source").text
    assert client.get(f"/api/runs/{run_id}/draws").status_code == 200
    assert client.get(f"/api/runs/{run_id}/bundle").status_code == 200


def test_a_run_with_bad_data_is_rejected_before_it_starts():
    response = client.post(
        "/api/runs",
        json={"spec": _spec(), "rows": [{"time": -5, "failure": 1}]},
    )
    assert response.status_code == 422
    assert response.json()["detail"]["errors"][0]["column"] == "time"


def test_examples_are_listed_and_served():
    listing = client.get("/api/examples").json()
    assert listing and all("title" in e and "likelihood" in e for e in listing)
    first = client.get(f"/api/examples/{listing[0]['id']}").json()
    assert first["spec"]["likelihood"] == listing[0]["likelihood"]
    assert first["rows"] and first["sampler"]["seed"] is not None
    assert client.get("/api/examples/no-such-example").status_code == 404
